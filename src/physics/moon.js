/**
 * 月球地心黃道座標（當日平春分點）：{ lon, lat (弧度), dist (km) }。
 * @param {number} jd 儒略日 (TT)
 */
export function moonEclipticOfDate(jd) {
  const T = (jd - J2000_JD) / JULIAN_CENTURY_DAYS;
  const T2 = T * T, T3 = T2 * T, T4 = T3 * T;
  const Lp = 218.3164477 + 481267.88123421 * T - 0.0015786 * T2 + T3 / 538841 - T4 / 65194000;
  const D = 297.8501921 + 445267.1114034 * T - 0.0018819 * T2 + T3 / 545868 - T4 / 113065000;
  const M = 357.5291092 + 35999.0502909 * T - 0.0001536 * T2 + T3 / 24490000;
  const Mp = 134.9633964 + 477198.8675055 * T + 0.0087414 * T2 + T3 / 69699 - T4 / 14712000;
  const F = 93.272095 + 483202.0175233 * T - 0.0036539 * T2 - T3 / 3526000 + T4 / 863310000;
  const A1 = 119.75 + 131.849 * T;
  const A2 = 53.09 + 479264.29 * T;
  const A3 = 313.45 + 481266.484 * T;
  const E = 1 - 0.002516 * T - 0.0000074 * T2;
  const E2 = E * E;

  const d = D * DEG, m = M * DEG, mp = Mp * DEG, f = F * DEG;
  let sl = 0, sr = 0, sb = 0;
  for (let k = 0; k < LR.length; k++) {
    const t = LR[k];
    const arg = t[0] * d + t[1] * m + t[2] * mp + t[3] * f;
    const em = t[1] === 0 ? 1 : (Math.abs(t[1]) === 1 ? E : E2);
    if (t[4]) sl += t[4] * em * Math.sin(arg);
    if (t[5]) sr += t[5] * em * Math.cos(arg);
  }
  for (let k = 0; k < B.length; k++) {
    const t = B[k];
    const arg = t[0] * d + t[1] * m + t[2] * mp + t[3] * f;
    const em = t[1] === 0 ? 1 : (Math.abs(t[1]) === 1 ? E : E2);
    sb += t[4] * em * Math.sin(arg);
  }
  sl += 3958 * Math.sin(A1 * DEG) + 1962 * Math.sin((Lp - F) * DEG) + 318 * Math.sin(A2 * DEG);
  sb += -2235 * Math.sin(Lp * DEG) + 382 * Math.sin(A3 * DEG) + 175 * Math.sin((A1 - F) * DEG)
    + 175 * Math.sin((A1 + F) * DEG) + 127 * Math.sin((Lp - Mp) * DEG) - 115 * Math.sin((Lp + Mp) * DEG);

  return {
    lon: (Lp + sl / 1e6) * DEG,
    lat: (sb / 1e6) * DEG,
    dist: 385000.56 + sr / 1000,
  };
}

/**
 * 當日平黃道座標 → J2000 黃道座標（Meeus 21.5 式之逆轉換）。
 * 輸入/輸出皆為直角座標。
 */
export function eclipticOfDateToJ2000(v, jd) {
  const T = (jd - J2000_JD) / JULIAN_CENTURY_DAYS;
  const eta = ((47.0029 - 0.06603 * T + 0.000598 * T * T) * T / 3600) * DEG;
  const Pi = (174.876384 + (3289.4789 * T + 0.60622 * T * T) / 3600) * DEG;
  const p = ((5029.0966 * T + 1.11113 * T * T - 0.000006 * T * T * T) / 3600) * DEG;
  // 當日座標以「Π + p − λ」角度表示 → 繞 x 軸旋轉 −η → 得到「Π − λ0」
  const lon = Math.atan2(v[1], v[0]);
  const rxy = Math.hypot(v[0], v[1]);
  const r = Math.hypot(rxy, v[2]);
  const lat = Math.atan2(v[2], rxy);
  const ang = Pi + p - lon;
  const X = Math.cos(lat) * Math.cos(ang);
  const Y = Math.cos(lat) * Math.sin(ang);
  const Z = Math.sin(lat);
  const ce = Math.cos(eta), se = Math.sin(eta);
  const x1 = X;
  const y1 = ce * Y + se * Z;
  const z1 = -se * Y + ce * Z;
  const lon0 = Pi - Math.atan2(y1, x1);
  const lat0 = Math.asin(Math.max(-1, Math.min(1, z1)));
  const c = Math.cos(lat0);
  return [r * c * Math.cos(lon0), r * c * Math.sin(lon0), r * Math.sin(lat0)];
}

/** 月球地心位置（km，J2000 黃道直角座標）。 */
export function moonGeocentric(jd) {
  const { lon, lat, dist } = moonEclipticOfDate(jd);
  const c = Math.cos(lat);
  const v = [dist * c * Math.cos(lon), dist * c * Math.sin(lon), dist * Math.sin(lat)];
  return eclipticOfDateToJ2000(v, jd);
}
